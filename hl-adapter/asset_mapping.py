def get_symbol(asset_id: int) -> str:
    """Get symbol for asset ID, or 'UNKNOWN_{id}' if not mapped."""
    return ASSET_MAP.get(asset_id, f"UNKNOWN_{asset_id}")


def get_asset_id(symbol: str) -> int:
    """Get asset ID for symbol, or -1 if not found."""
    return SYMBOL_TO_ID.get(symbol, -1)
